/* tooling/pages/index.mjs — every generated page of the site, for Eleventy.
 *
 * Each module default-exports `async function pages()` returning `[{ path, html }]`, where `path`
 * is the output file relative to the site root (`fr/bepo/index.html`). Modules only READ sources
 * (content/, 11ty/client/, hand-written pages in 11ty/site/); Eleventy is the only writer.
 *
 * `PAGES=roadmaps,games npx eleventy` builds only those modules (quicker while working on one).
 */
export const MODULES = ['roadmaps', 'families', 'tasters', 'typing-tests', 'guides', 'games', 'progress', 'legal', 'en-redirects'];

export async function allPages() {
  const only = process.env.PAGES === 'none' ? [] : process.env.PAGES ? process.env.PAGES.split(',').map(name => name.trim()).filter(Boolean) : null;
  for (const name of only || []) if (!MODULES.includes(name)) throw new Error(`PAGES: no module ${name} (have ${MODULES.join(', ')})`);
  const seen = new Map();
  const out = [];
  for (const name of only || MODULES) {
    const { default: pages } = await import(`./${name}.mjs`);
    for (const page of await pages()) {
      if (!/^([a-z0-9][a-z0-9._-]*\/)*index\.html$/.test(page.path)) throw new Error(`${name}: bad page path ${page.path}`);
      if (seen.has(page.path)) throw new Error(`${page.path} generated by both ${seen.get(page.path)} and ${name}`);
      seen.set(page.path, name);
      out.push({ path: page.path, html: page.html, module: name });
    }
  }
  return out;
}
